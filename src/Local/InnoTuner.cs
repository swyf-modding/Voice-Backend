    /// <summary>
    /// Turns one reference clip into a Kokoro voice: 510 rows of 256 style values, the same layout the
    /// stock <c>voices/*.bin</c> files use.
    /// </summary>
    /// <remarks>
    /// A port of the inno-kokoro zero-shot tuner (github.com/remsky/inno-kokoro v0.2.0, weights
    /// remsky/kokoro-inno-clone-tuner v0.2.0). Upstream is PyTorch plus scipy plus parselmouth; here only
    /// the speaker encoder stayed neural and runs as ONNX on the runtime the game already ships
    /// (<c>assets/inno/encoder.onnx</c>), while everything around it is arithmetic this file does:
    ///
    /// <list type="number">
    /// <item>kaldi fbank at 16 kHz (int16 scale, 25/10 ms frames, per-frame mean removal, 0.97 pre-emphasis,
    /// hamming, 512-point power spectrum, 80 triangular mel filters 20 Hz..8 kHz, log, per-utterance CMN);</item>
    /// <item>the encoder graph, which returns a unit 512-wide embedding in UniSpeech-SAT-sv space;</item>
    /// <item>the style head (512 -> 512 GELU -> 256) plus the reference's spectral tilt along the learned
    /// tilt direction, giving the timbre half of the style vector;</item>
    /// <item>F0 mean and spread in semitones, syllable rate and the tracking ceiling from the cepstral
    /// fundamental, which pick a nonnegative blend of the stock packs' predictor rows.</item>
    /// </list>
    ///
    /// The predictor half is the blend itself: every one of the 510 rows gets the same 128 numbers, and every
    /// row gets the same 128 timbre numbers, which is what a stock Kokoro voice looks like (all its rows are
    /// the same vector) and what the tuner learned to produce.
    ///
    /// The upstream prosody head (<c>head=True</c>, <c>head_stats</c> through parselmouth/Praat) is
    /// deliberately left out: it costs a Praat-pitch measurement of the reference in 6 s chunks and buys
    /// 0.5 st of F0 spread accuracy instead of the 0.65 st this tracker reads (see the model card). Since the
    /// head only nudges the predictor half, this is the documented <c>head=False</c> behaviour of v0.2.0, and
    /// the mod matches that reference by default.
    ///
    /// The blend tables, the style head and the tilt direction come from <c>assets/inno/tuner.bin</c>;
    /// <c>assets/inno/default-voice.bin</c> is the stock af_heart pack the mod falls back to when a caller has
    /// no usable reference. All three files are generated by <c>tools/export-inno.py</c>, which also checks the
    /// encoder against torch. Enrolment is a few hundred milliseconds of DSP and one encoder run: 162 ms for an
    /// 8 s 24 kHz clip, 670 ms for 30 s at 44.1 kHz.
    ///
    /// One instance serves every caller, so <see cref="Enroll"/> keeps nothing in a field: all buffers are
    /// locals, the encoder session is safe to run from several threads (see <see cref="OrtSession"/>), and the
    /// only shared state is the read-only FFT twiddle cache.
    ///
    /// The arithmetic here is double precision, where upstream uses float32 tensors. The two agree to 1e-7 on
    /// the embedding, the style vector and every prosody measurement, and to 1e-7 on the blend weights; the one
    /// place they can part is a frame whose pitch candidates tie inside a few 1e-8, where the float32
    /// correlation sums and the double ones can pick different lags. An exact evaluation of the tie is the
    /// better answer, so this file keeps the double sums rather than imitating PyTorch's reduction order.
    /// The predictor quirk that follows is visible in the packaged rows too: they are stored as float16, as the
    /// upstream blend table is, so a rebuilt pack differs from a float32 reference by about 3e-4 in that half
    /// and by 1e-7 in the timbre half.
    /// </remarks>
    internal sealed class InnoTuner : IDisposable
    {
        /// <summary>Sample rate the speaker encoder and the pitch tracker work at.</summary>
        internal const int EncoderRate = 16000;

        /// <summary>Sample rate Kokoro renders at, and the rate the spectral tilt is measured at.</summary>
        internal const int KokoroRate = 24000;

        /// <summary>Only the first 30 s of a reference are used, as upstream: a long clip adds nothing.</summary>
        internal const double ReferenceSeconds = 30.0;

        /// <summary>Below this the prosody measurements are too short to mean anything.</summary>
        internal const double MinimumSeconds = 3.0;

        /// <summary>The shortest reference upstream recommends; shorter ones enrol but read noisily.</summary>
        internal const double RecommendedSeconds = 5.0;

        internal const int MelBins = 80;
        private const int FrameLength = 400;
        private const int FrameHop = 160;
        private const int SpectrumSize = 512;
        private const int SpectrumBins = 256;
        private const double PreEmphasis = 0.97;
        private const float PowerEpsilon = 1.1920929E-07f;

        private const int PitchHop = 320;
        private const int PitchWindow = 2 * PitchHop;
        private const int MedianFrames = 30;
        private const double LagTolerance = 0.9;
        private const double F0Min = 60.0;
        private const double F0Max = 400.0;
        private const double SemitoneReference = 100.0;

        private const int TiltWindow = 1024;
        private const int TiltHop = 256;
        private const double TiltBandLow = 300.0;
        private const double TiltBandHigh = 4000.0;

        private const int CepstrumLength = 4096;
        private const double CepstrumMinPeak = 0.01;
        private const double CepstrumCeiling = 1.6;
        private const double CepstrumTolerance = 0.25;

        private const double TiltSdWarn = 2.5;

        // The mod builds against the game's stripped mscorlib with -nostdlib+, which has no Pi and
        // no double/float constants beyond the numbers themselves.
        private const double Pi = 3.14159265358979323846;
        private const double LnToLog2 = 1.4426950408889634; // 1 / ln 2
        private const double Huge = 1e308;
        private const int MinimumPacks = 3;
        private const double WeightFloor = 1e-3;

        private static readonly byte[] Magic = Encoding.ASCII.GetBytes("INNOTUN1");

        private OrtSession _encoder;
        private int _packCount;
        private int _rowCount;
        private int _embedDim;
        private int _hiddenDim;
        private int _styleDim;
        private int _half;
        private float[] _styleW0;
        private float[] _styleB0;
        private float[] _styleW2;
        private float[] _styleB2;
        private float[] _tiltDir;
        private float[] _packStats;
        private float[] _packGrades;
        private ushort[] _rows;
        private string[] _names;
        private double _blendGate;
        private double _gradePenalty;
        private double _tiltMean;
        private double _tiltSd;
        private double[] _blendScale;
        private Action<string> _warn = delegate { };

        private InnoTuner()
        {
        }

        /// <summary>Rows in the pack: one per phoneme count Kokoro can be given.</summary>
        internal int RowCount { get { return _rowCount; } }

        /// <summary>Values per row, 128 timbre then 128 predictor.</summary>
        internal int StyleLength { get { return _styleDim; } }

        /// <summary>Stock pack names the blend can pick from.</summary>
        internal string[] PackNames { get { return (string[])_names.Clone(); } }

        /// <summary>
        /// Reads <paramref name="tunerPath"/> and opens the encoder session in <paramref name="encoderPath"/>.
        /// </summary>
        /// <param name="encoderPath">assets/inno/encoder.onnx: fbank features [B, 80, T] -> unit embedding [B, 512].</param>
        /// <param name="tunerPath">assets/inno/tuner.bin: style head, tilt direction, blend tables, metadata.</param>
        /// <param name="device">Where the encoder runs. The graph is small; the CPU copy is what ships.</param>
        /// <param name="threads">Intra-op threads for the encoder session, 0 for the runtime's default.</param>
        /// <param name="warn">Receives non-fatal complaints: an unusual reference, or a graph on the CPU instead of the GPU.</param>
        internal static InnoTuner Load(string encoderPath, string tunerPath, OrtDevice device, int threads, Action<string> warn)
        {
            InnoTuner tuner = new InnoTuner();
            if (warn != null) tuner._warn = warn;
            tuner.ReadTables(tunerPath);
            tuner._encoder = OrtSession.Create(encoderPath, device, threads, tuner._warn);
            return tuner;
        }

        /// <summary>
        /// Enrols <paramref name="samples"/> (mono float in [-1, 1] at <paramref name="sampleRate"/>) and returns
        /// the pack: <see cref="RowCount"/> rows of <see cref="StyleLength"/> floats, row-major, the layout of a
        /// Kokoro <c>voices/*.bin</c>.
        /// </summary>
        /// <param name="topPacks">
        /// The stock packs that carry weight, strongest first, as <c>name</c> strings, for the log. Anything at or
        /// below 1e-3 is dropped, as upstream does, and dropped packs contribute nothing to the predictor half.
        /// </param>
        /// <exception cref="ArgumentException">The clip is shorter than 3 s, or has no measurable speech.</exception>
        internal float[] Enroll(float[] samples, int sampleRate, out string[] topPacks)
        {
            if (_encoder == null) throw new ObjectDisposedException("InnoTuner");
            if (samples == null) throw new ArgumentNullException("samples");
            if (sampleRate <= 0) throw new ArgumentOutOfRangeException("sampleRate");

            double duration = samples.Length / (double)sampleRate;
            if (duration < MinimumSeconds)
            {
                throw new ArgumentException(string.Format(CultureInfo.InvariantCulture,
                    "Reference is {0:0.0} s; need at least {1:0} s to measure prosody.",
                    duration, MinimumSeconds), "samples");
            }
            if (duration < RecommendedSeconds)
            {
                _warn(string.Format(CultureInfo.InvariantCulture,
                    "Reference is {0:0.0} s; {1:0} s or more is recommended.", duration, RecommendedSeconds));
            }

            int used = Math.Min(samples.Length, (int)Math.Round(ReferenceSeconds * sampleRate));
            float[] wav = samples;
            if (used != samples.Length)
            {
                wav = new float[used];
                Array.Copy(samples, wav, used);
            }

            // Timbre: encoder embedding -> style head, then the tilt shift along the learned direction.
            float[] encoderInput = PrepareFeatures(wav, sampleRate);
            int frames = encoderInput.Length / MelBins;
            float[] embedding = Embed(encoderInput, frames);
            double tilt = Tilt(wav, sampleRate);
            double tiltSd = (tilt - _tiltMean) / _tiltSd;
            if (Math.Abs(tiltSd) > TiltSdWarn)
            {
                _warn(string.Format(CultureInfo.InvariantCulture,
                    "Reference tilt is {0:0.0} dB/oct ({1:+0.0;-0.0} sd, {2}); archival or heavily filtered sources " +
                    "push the timbre past what the tuner was trained on.",
                    tilt, tiltSd, tiltSd < 0 ? "dark" : "bright"));
            }
            float[] style = Style(embedding, tiltSd);

            // Prosody: one tracking ceiling for both measurements, or they can read different octaves.
            double meanSt;
            double spreadSt;
            double voiced;
            Prosody(wav, sampleRate, out meanSt, out spreadSt, out voiced);
            double syllableRate = Rate(wav, sampleRate);
            double[] target = { meanSt, spreadSt, syllableRate };

            double[] weights;
            int[] chosen;
            BlendWeights(target, out chosen, out weights);

            float[] predictor = new float[_rowCount * _half];
            for (int c = 0; c < chosen.Length; c++)
            {
                int source = chosen[c];
                float weight = (float)weights[c];
                int start = source * _rowCount * _half;
                for (int j = 0; j < predictor.Length; j++)
                {
                    predictor[j] += weight * HalfToFloat(_rows[start + j]);
                }
            }

            float[] pack = new float[_rowCount * _styleDim];
            for (int row = 0; row < _rowCount; row++)
            {
                int to = row * _styleDim;
                for (int k = 0; k < _half; k++)
                {
                    pack[to + k] = style[k];
                    pack[to + _half + k] = predictor[row * _half + k];
                }
            }

            topPacks = new string[chosen.Length];
            for (int c = 0; c < chosen.Length; c++)
            {
                topPacks[c] = _names[chosen[c]];
            }
            return pack;
        }

        public void Dispose()
        {
            if (_encoder != null)
            {
                _encoder.Dispose();
                _encoder = null;
            }
        }

        // ---------------------------------------------------------------- tuner.bin

        /// <summary>Reads the flat table file. Layout documented in tools/export-inno.py.</summary>
        private void ReadTables(string path)
        {
            using (FileStream stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read))
            using (BinaryReader reader = new BinaryReader(stream))
            {
                byte[] magic = reader.ReadBytes(Magic.Length);
                if (magic.Length != Magic.Length)
                {
                    throw new InvalidDataException("Tuner file is truncated: " + path);
                }
                for (int i = 0; i < Magic.Length; i++)
                {
                    if (magic[i] != Magic[i])
                    {
                        throw new InvalidDataException("Not an inno-kokoro tuner file: " + path);
                    }
                }

                _packCount = reader.ReadInt32();
                _rowCount = reader.ReadInt32();
                _embedDim = reader.ReadInt32();
                _hiddenDim = reader.ReadInt32();
                _styleDim = reader.ReadInt32();
                _half = reader.ReadInt32();
                int nameBytes = reader.ReadInt32();
                _blendGate = reader.ReadSingle();
                _gradePenalty = reader.ReadSingle();
                _tiltMean = reader.ReadSingle();
                _tiltSd = reader.ReadSingle();
                _blendScale = new double[3];
                for (int i = 0; i < 3; i++) _blendScale[i] = reader.ReadSingle();

                if (_packCount <= 0 || _rowCount <= 0 || _embedDim != 512 || _hiddenDim <= 0 ||
                    _styleDim != 2 * _half || _half <= 0 || nameBytes <= 0 ||
                    _blendScale[0] <= 0 || _blendScale[1] <= 0 || _blendScale[2] <= 0 || _tiltSd <= 0)
                {
                    throw new InvalidDataException("Tuner file header is not usable: " + path);
                }

                long expected = 64L
                    + 4L * (_hiddenDim * _embedDim + _hiddenDim + _styleDim * _hiddenDim + _styleDim + _styleDim)
                    + 4L * (3 * _packCount + _packCount)
                    + 2L * _packCount * _rowCount * _half
                    + nameBytes;
                if (stream.Length != expected)
                {
                    throw new InvalidDataException(string.Format(CultureInfo.InvariantCulture,
                        "Tuner file is {0} bytes; its header describes {1}.", stream.Length, expected));
                }

                _styleW0 = ReadFloats(reader, _hiddenDim * _embedDim);
                _styleB0 = ReadFloats(reader, _hiddenDim);
                _styleW2 = ReadFloats(reader, _styleDim * _hiddenDim);
                _styleB2 = ReadFloats(reader, _styleDim);
                _tiltDir = ReadFloats(reader, _styleDim);
                _packStats = ReadFloats(reader, 3 * _packCount);
                _packGrades = ReadFloats(reader, _packCount);
                _rows = new ushort[_packCount * _rowCount * _half];
                for (int i = 0; i < _rows.Length; i++)
                {
                    ushort half = reader.ReadUInt16();
                    if (((half >> 10) & 0x1F) == 0x1F)
                    {
                        // A half with the top exponent is infinity or NaN. Rejecting it here is what lets
                        // HalfToFloat stay finite-only: the game's mscorlib has no NaN or infinity constant,
                        // and the exporter writes these rows from a finite float32 table.
                        throw new InvalidDataException(
                            "Tuner file has a non-finite predictor value at row " + i + ": " + path);
                    }
                    _rows[i] = half;
                }

                byte[] blob = reader.ReadBytes(nameBytes);
                string[] names = Encoding.UTF8.GetString(blob).Split('\0');
                List<string> list = new List<string>(_packCount);
                for (int i = 0; i < names.Length; i++)
                {
                    if (names[i].Length != 0) list.Add(names[i]);
                }
                if (list.Count != _packCount)
                {
                    throw new InvalidDataException(string.Format(CultureInfo.InvariantCulture,
                        "Tuner file names {0} packs; the header says {1}.", list.Count, _packCount));
                }
                _names = list.ToArray();
            }
        }

        private static float[] ReadFloats(BinaryReader reader, int count)
        {
            float[] values = new float[count];
            for (int i = 0; i < count; i++) values[i] = reader.ReadSingle();
            return values;
        }

        // ---------------------------------------------------------------- the neural half

        /// <summary>Resamples to <see cref="EncoderRate"/>, cuts to 30 s and runs the fbank front end.</summary>
        internal float[] PrepareFeatures(float[] wav, int sampleRate)
        {
            float[] mono = Resample(wav, sampleRate, EncoderRate);
            int keep = (int)Math.Round(ReferenceSeconds * EncoderRate);
            if (mono.Length > keep)
            {
                float[] cut = new float[keep];
                Array.Copy(mono, cut, keep);
                mono = cut;
            }

            int frames;
            return Fbank(mono, out frames);
        }

        /// <summary>Runs the encoder graph on fbank features laid out [80, frames] and returns the unit embedding.</summary>
        internal float[] Embed(float[] features, int frames)
        {
            if (features == null || features.Length != MelBins * frames || frames <= 0)
            {
                throw new ArgumentException("Feature tensor does not match its frame count.", "features");
            }

            OrtTensor input = OrtTensor.Float(features, new long[] { 1, MelBins, frames });
            OrtTensor[] outputs = null;
            try
            {
                outputs = _encoder.Run(new[] { input });
                if (outputs.Length != 1)
                {
                    throw new InvalidOperationException(string.Format(CultureInfo.InvariantCulture,
                        "Encoder graph has {0} outputs; expected one.", outputs.Length));
                }
                long[] shape = outputs[0].ActualShape();
                if (shape.Length != 2 || shape[1] != _embedDim)
                {
                    throw new InvalidOperationException(string.Format(CultureInfo.InvariantCulture,
                        "Encoder graph returned [{0}]; expected [1, {1}].", string.Join(", ", Array.ConvertAll(shape,
                        delegate (long v) { return v.ToString(CultureInfo.InvariantCulture); })), _embedDim));
                }
                return outputs[0].ToFloats();
            }
            finally
            {
                if (outputs != null)
                {
                    for (int i = 0; i < outputs.Length; i++) outputs[i].Dispose();
                }
                input.Dispose();
            }
        }

        /// <summary>
        /// The style head (512 -> 512 GELU -> 256) on the embedding, plus the tilt direction scaled by how many
        /// standard deviations the reference's brightness is from the tuner's average.
        /// </summary>
        internal float[] Style(float[] embedding, double tiltSd)
        {
            if (embedding == null || embedding.Length != _embedDim)
            {
                throw new ArgumentException("Embedding is not " + _embedDim + " wide.", "embedding");
            }

            float[] hidden = new float[_hiddenDim];
            for (int o = 0; o < _hiddenDim; o++)
            {
                int row = o * _embedDim;
                double sum = _styleB0[o];
                for (int i = 0; i < _embedDim; i++) sum += _styleW0[row + i] * embedding[i];
                hidden[o] = Gelu(sum);
            }

            float[] style = new float[_styleDim];
            float shift = (float)tiltSd;
            for (int o = 0; o < _styleDim; o++)
            {
                int row = o * _hiddenDim;
                double sum = _styleB2[o];
                for (int i = 0; i < _hiddenDim; i++) sum += _styleW2[row + i] * hidden[i];
                style[o] = (float)sum + _tiltDir[o] * shift;
            }
            return style;
        }

        /// <summary>Exact GELU, which is what torch.nn.GELU applies by default.</summary>
        private static float Gelu(double x)
        {
            return (float)(0.5 * x * (1.0 + Erf(x * 0.70710678118654752)));
        }

        /// <summary>
        /// erf to double precision: Maclaurin series below 3 (terms fall to 1e-4 of the peak by n = 20, so the
        /// cancellation costs about 4 of 16 digits), Laplace continued fraction above it.
        /// </summary>
        private static double Erf(double x)
        {
            if (x < 0) return -Erf(-x);
            if (x == 0) return 0;
            if (x <= 3.0)
            {
                double sum = x;
                double term = x;
                double x2 = x * x;
                for (int n = 1; n < 60; n++)
                {
                    term *= -x2 / n;
                    double add = term / (2 * n + 1);
                    sum += add;
                    if (Math.Abs(add) < 1e-17 * Math.Abs(sum)) break;
                }
                return 1.1283791670955126 * sum; // 2/sqrt(pi)
            }

            // erfc(x) = exp(-x^2)/sqrt(pi) * 1/(x + (1/2)/(x + 1/(x + (3/2)/(x + ...)))) via modified Lentz.
            double tiny = 1e-300;
            double f = x;
            double c = x;
            double d = 0;
            double cf = tiny;
            for (int n = 1; n < 300; n++)
            {
                double a = 0.5 * n;
                d = x + a * d;
                if (Math.Abs(d) < tiny) d = tiny;
                c = x + a / c;
                if (Math.Abs(c) < tiny) c = tiny;
                d = 1.0 / d;
                double delta = c * d;
                f *= delta;
                if (Math.Abs(delta - 1.0) < 1e-16) break;
            }
            return 1.0 - Math.Exp(-x * x) * 0.56418958354775628 / f; // 1/sqrt(pi)
        }

        // ---------------------------------------------------------------- fbank front end

        /// <summary>
        /// kaldi fbank, the front end upstream keeps in torch: 25 ms hamming frames every 10 ms of
        /// int16-scaled samples, per-frame mean removal, 0.97 pre-emphasis, 512-point power spectrum,
        /// 80 triangular mel filters from 20 Hz to 8 kHz, natural log clamped at the float epsilon, then
        /// per-utterance cepstral mean normalisation.
        /// </summary>
        /// <param name="mono16k">Samples at <see cref="EncoderRate"/>.</param>
        /// <param name="frames">Number of frames produced.</param>
        /// <returns>Features laid out [80, frames], which is the encoder graph's input.</returns>
        internal static float[] Fbank(float[] mono16k, out int frames)
        {
            if (mono16k == null) throw new ArgumentNullException("mono16k");
            frames = mono16k.Length < FrameLength ? 0 : (mono16k.Length - FrameLength) / FrameHop + 1;
            if (frames <= 0)
            {
                throw new ArgumentException("Need at least " + FrameLength + " samples for one fbank frame.", "mono16k");
            }

            double[] window = new double[FrameLength];
            for (int n = 0; n < FrameLength; n++)
            {
                window[n] = 0.54 - 0.46 * Math.Cos(2.0 * Pi * n / (FrameLength - 1)); // periodic=False
            }
            double[] banks = MelBanks();

            FftPlan plan = FftPlan.Get(SpectrumSize);
            double[] re = new double[SpectrumSize];
            double[] im = new double[SpectrumSize];
            double[] power = new double[SpectrumBins];
            double[] frame = new double[FrameLength];
            float[] features = new float[MelBins * frames];

            for (int t = 0; t < frames; t++)
            {
                int at = t * FrameHop;
                double mean = 0;
                for (int n = 0; n < FrameLength; n++) mean += mono16k[at + n] * 32768.0;
                mean /= FrameLength;
                for (int n = 0; n < FrameLength; n++) frame[n] = mono16k[at + n] * 32768.0 - mean;

                // Pre-emphasis against the frame's own first sample, which is what replicating the edge does.
                double first = frame[0];
                double previous = first;
                for (int n = 0; n < FrameLength; n++)
                {
                    double current = frame[n];
                    re[n] = (current - PreEmphasis * previous) * window[n];
                    previous = current;
                    im[n] = 0;
                }
                for (int n = FrameLength; n < SpectrumSize; n++)
                {
                    re[n] = 0;
                    im[n] = 0;
                }

                plan.Forward(re, im);
                for (int b = 0; b < SpectrumBins; b++) power[b] = re[b] * re[b] + im[b] * im[b];

                int bankRow = 0;
                for (int m = 0; m < MelBins; m++)
                {
                    double sum = 0;
                    for (int b = 0; b < SpectrumBins; b++) sum += banks[bankRow + b] * power[b];
                    bankRow += SpectrumBins;
                    features[m * frames + t] = (float)(sum > PowerEpsilon ? Math.Log(sum) : Math.Log(PowerEpsilon));
                }
            }

            // Per-utterance CMN: mean over time of each mel bin.
            for (int m = 0; m < MelBins; m++)
            {
                int row = m * frames;
                double sum = 0;
                for (int t = 0; t < frames; t++) sum += features[row + t];
                float mean = (float)(sum / frames);
                for (int t = 0; t < frames; t++) features[row + t] -= mean;
            }
            return features;
        }

        /// <summary>
        /// The 80 triangular mel filters, [80, 256] row-major, laid out exactly as upstream builds them: the
        /// lower and upper edges of filter m are <c>mel(20) + m*d</c> with <c>d</c> covering 80 bands plus one
        /// up to 8 kHz, evaluated on the mel scale of the 256 bins below Nyquist (kaldi drops the last bin).
        /// </summary>
        private static double[] MelBanks()
        {
            double low = Mel(20.0);
            double d = (Mel(8000.0) - low) / (MelBins + 1);
            double[] banks = new double[MelBins * SpectrumBins];
            for (int m = 0; m < MelBins; m++)
            {
                double left = low + m * d;
                double right = left + 2 * d;
                int row = m * SpectrumBins;
                for (int b = 0; b < SpectrumBins; b++)
                {
                    double f = Mel(b * EncoderRate / (double)SpectrumSize);
                    double up = (f - left) / d;
                    double down = (right - f) / d;
                    double v = up < down ? up : down;
                    banks[row + b] = v > 0 ? v : 0;
                }
            }
            return banks;
        }

        private static double Mel(double hz)
        {
            return 1127.0 * Math.Log(1.0 + hz / 700.0);
        }

        // ---------------------------------------------------------------- resampling

        /// <summary>
        /// scipy.signal.resample_poly as upstream calls it: up by <c>rateOut/g</c>, low-pass with a Kaiser(5)
        /// windowed sinc at <c>1/max(up, down)</c> of the new Nyquist, down by <c>rateIn/g</c>, zero phase, and
        /// the first output sample sitting on the first input sample.
        /// </summary>
        internal static float[] Resample(float[] x, int rateIn, int rateOut)
        {
            if (rateIn == rateOut) return x;
            if (rateIn <= 0 || rateOut <= 0) throw new ArgumentOutOfRangeException("rateOut");

            int g = Gcd(rateIn, rateOut);
            int up = rateOut / g;
            int down = rateIn / g;
            int maxRate = up > down ? up : down;
            int halfLength = 10 * maxRate;
            int taps = 2 * halfLength + 1;
            double[] h = LowPass(taps, 1.0 / maxRate, up);

            long scaled = (long)x.Length * up;
            long outLength = scaled / down + (scaled % down != 0 ? 1 : 0);
            float[] y = new float[outLength];
            for (long i = 0; i < outLength; i++)
            {
                long origin = i * down + halfLength;
                int phase = (int)(origin % up);
                double sum = 0;
                for (int k = phase; k < taps; k += up)
                {
                    long j = (origin - k) / up;
                    if (j < 0) break;
                    if (j < x.Length) sum += h[k] * x[j];
                }
                y[i] = (float)sum;
            }
            return y;
        }

        /// <summary>
        /// A Kaiser(5)-windowed sinc low-pass, unity at DC, scaled by <paramref name="gain"/>. The window is
        /// applied before the DC normalisation, as scipy's firwin does: on the short filters (61 taps for
        /// 24 kHz to 16 kHz) the two orders differ by 2%.
        /// </summary>
        private static double[] LowPass(int taps, double cutoff, int gain)
        {
            double alpha = 0.5 * (taps - 1);
            const double beta = 5.0;
            double denominator = BesselI0(beta);
            double[] h = new double[taps];
            double sum = 0;
            for (int k = 0; k < taps; k++)
            {
                double t = k - alpha;
                double r = 2.0 * k / (taps - 1) - 1.0;
                h[k] = cutoff * Sinc(cutoff * t) * BesselI0(beta * Math.Sqrt(1.0 - r * r)) / denominator;
                sum += h[k];
            }
            for (int k = 0; k < taps; k++) h[k] = h[k] / sum * gain;
            return h;
        }

        private static double Sinc(double t)
        {
            if (t == 0) return 1.0;
            double pt = Pi * t;
            return Math.Sin(pt) / pt;
        }

        /// <summary>Modified Bessel function of the first kind, order 0, by its series.</summary>
        private static double BesselI0(double x)
        {
            double sum = 1.0;
            double term = 1.0;
            double half = x * 0.5;
            for (int k = 1; k < 64; k++)
            {
                term *= half / k;
                double add = term * term;
                sum += add;
                if (add < 1e-18 * sum) break;
            }
            return sum;
        }

        private static int Gcd(int a, int b)
        {
            while (b != 0)
            {
                int t = a % b;
                a = b;
                b = t;
            }
            return a;
        }

