        /// <summary>F0 mean and spread in semitones over the voiced frames, plus the voiced fraction.</summary>
        internal static void Prosody(float[] wav, int sampleRate, out double meanSt, out double spreadSt, out double voicedFraction)
        {
            float[] mono = Resample(wav, sampleRate, EncoderRate);
            double ceiling = Ceiling(wav, sampleRate);
            double floor = F0Min;
            meanSt = 0;
            spreadSt = 0;
            voicedFraction = 0;

            for (int pass = 0; pass < 2; pass++)
            {
                double[] f0;
                double[] energy;
                TrackF0(mono, floor, ceiling, out f0, out energy);

                double maxEnergy = 0;
                for (int i = 0; i < energy.Length; i++)
                {
                    if (energy[i] > maxEnergy) maxEnergy = energy[i];
                }
                double gate = 0.1 * maxEnergy;

                double[] semitones = new double[f0.Length];
                int count = 0;
                for (int i = 0; i < f0.Length; i++)
                {
                    if (energy[i] > gate && f0[i] > floor && f0[i] < ceiling)
                    {
                        semitones[count++] = Semitones(f0[i]);
                    }
                }
                if (count == 0)
                {
                    meanSt = 0;
                    spreadSt = 0;
                    voicedFraction = 0;
                    return;
                }

                double sum = 0;
                for (int i = 0; i < count; i++) sum += semitones[i];
                meanSt = sum / count;
                if (count > 1)
                {
                    double variance = 0;
                    for (int i = 0; i < count; i++)
                    {
                        double d = semitones[i] - meanSt;
                        variance += d * d;
                    }
                    spreadSt = Math.Sqrt(variance / (count - 1)); // torch's unbiased default
                }
                else
                {
                    spreadSt = 0;
                }
                voicedFraction = count / (double)f0.Length;

                // Pass 2 raises the floor to 0.65x the upper-quartile F0 to drop octave-down picks on high voices.
                double q75 = Quantile(semitones, count, 0.75);
                floor = Math.Min(0.65 * FromSemitones(q75), 180.0);
            }
        }

        private static double Semitones(double hz)
        {
            return 12.0 * Math.Log(hz / SemitoneReference) * LnToLog2;
        }

        private static double FromSemitones(double semitones)
        {
            return SemitoneReference * Math.Pow(2.0, semitones / 12.0);
        }

        /// <summary>
        /// The normalised cross-correlation pitch tracker: 640-sample frames every 20 ms, lags spanning
        /// <paramref name="lo"/>..<paramref name="hi"/> Hz, submultiple resolution over k in 2..4, then 600 ms
        /// of median smoothing on the lag. One estimate per frame.
        /// </summary>
        private static void TrackF0(float[] w, double lo, double hi, out double[] f0, out double[] energy)
        {
            int frameCount = w.Length / PitchHop;
            if (frameCount <= 0)
            {
                f0 = new double[0];
                energy = new double[0];
                return;
            }

            int lagLow = (int)(EncoderRate / hi);
            int lagHigh = (int)(EncoderRate / lo);
            if (lagLow < 1) lagLow = 1;
            if (lagHigh < lagLow) lagHigh = lagLow; // lo above hi: one lag is all the range can express
            int lagCount = lagHigh - lagLow + 1;
            double[] correlation = new double[lagCount];
            double[] x = new double[PitchWindow];
            double[] bestLag = new double[frameCount];
            energy = new double[frameCount];

            for (int i = 0; i < frameCount; i++)
            {
                int at = i * PitchHop;
                double xEnergy = 0;
                for (int n = 0; n < PitchWindow; n++)
                {
                    int index = at + n;
                    double v = index < w.Length ? w[index] : 0.0;
                    x[n] = v;
                    xEnergy += v * v;
                }

                for (int lag = lagLow; lag <= lagHigh; lag++)
                {
                    double xy = 0;
                    double yy = 0;
                    for (int n = 0; n < PitchWindow; n++)
                    {
                        int index = at + lag + n;
                        double v = index < w.Length ? w[index] : 0.0;
                        xy += x[n] * v;
                        yy += v * v;
                    }
                    double norm = Math.Sqrt(xEnergy * yy);
                    correlation[lag - lagLow] = xy / (norm > 1e-8 ? norm : 1e-8);
                }

                bestLag[i] = lagLow + FundamentalIndex(correlation, lagCount, lagLow, LagTolerance);
            }

            // RMS energy per hop, dropping the partial last frame.
            for (int i = 0; i < frameCount; i++)
            {
                double sum = 0;
                int at = i * PitchHop;
                for (int n = 0; n < PitchHop; n++)
                {
                    double v = w[at + n];
                    sum += v * v;
                }
                energy[i] = Math.Sqrt(sum / PitchHop);
            }

            double[] window = new double[MedianFrames];
            double[] scratch = new double[MedianFrames];
            int front = MedianFrames / 2;
            f0 = new double[frameCount];
            for (int i = 0; i < frameCount; i++)
            {
                for (int n = 0; n < MedianFrames; n++)
                {
                    int j = i - front + n;
                    if (j < 0) j = 0;
                    else if (j >= frameCount) j = frameCount - 1;
                    window[n] = bestLag[j];
                }
                f0[i] = EncoderRate / LowerMedian(window, MedianFrames, scratch);
            }
        }

        /// <summary>
        /// Peak index resolved to the period rather than a multiple of it: a 2x or 3x lag scores as well as the
        /// true period, and better when the period falls between samples, so the shortest submultiple scoring
        /// within <paramref name="tolerance"/> of the peak wins. <paramref name="off"/> is the lag that the
        /// first column stands for.
        /// </summary>
        private static int FundamentalIndex(double[] row, int length, int off, double tolerance)
        {
            int best = 0;
            for (int i = 1; i < length; i++)
            {
                if (row[i] > row[best]) best = i;
            }
            double peak = row[best];
            int index = best;

            for (int k = 2; k <= 4; k++)
            {
                int candidate = RoundHalfEven((best + off) / (double)k) - off;
                double value = -Huge;
                int pick = -1;
                for (int d = -1; d <= 1; d++)
                {
                    int j = candidate + d;
                    if (j < 0) j = 0;
                    else if (j >= length) j = length - 1;
                    if (pick < 0 || row[j] > value)
                    {
                        value = row[j];
                        pick = j;
                    }
                }
                if (candidate >= 0 && peak > 0 && value >= tolerance * peak) index = pick;
            }
            return index;
        }

        /// <summary>Round half to even, which is what torch.round does and what the submultiple lookup needs.</summary>
        private static int RoundHalfEven(double value)
        {
            if (value < 0) return -RoundHalfEven(-value);
            double lower = Math.Floor(value);
            double fraction = value - lower;
            int whole = (int)lower;
            if (fraction > 0.5) return whole + 1;
            if (fraction < 0.5) return whole;
            return (whole & 1) == 0 ? whole : whole + 1;
        }

        /// <summary>
        /// Tracking ceiling in Hz: the harmonic comb of the cepstrum sets it to 1.6x its fundamental when the comb
        /// is clear, because band-limited audio can make the lag tracker read frames an octave high.
        /// </summary>
        internal static double Ceiling(float[] wav, int sampleRate)
        {
            float[] mono = Resample(wav, sampleRate, EncoderRate);
            double fundamental;
            double peak;
            CepstralF0(mono, out fundamental, out peak);
            return peak > CepstrumMinPeak ? Math.Min(F0Max, CepstrumCeiling * fundamental) : F0Max;
        }

        /// <summary>
        /// Fundamental from harmonic spacing: the cepstral peak over the loudest 30% of 4096-sample frames, on
        /// the 60..300 Hz quefrency band. Immune to the octave errors that fool the lag tracker on band-limited
        /// audio, but biased toward the modal rather than the mean F0.
        /// </summary>
        private static void CepstralF0(float[] w, out double hz, out double peak)
        {
            hz = 0;
            peak = 0;
            int frames = w.Length / CepstrumLength;
            if (frames == 0) return;

            double[] frameEnergy = new double[frames];
            for (int f = 0; f < frames; f++)
            {
                double sum = 0;
                int at = f * CepstrumLength;
                for (int n = 0; n < CepstrumLength; n++)
                {
                    double v = w[at + n];
                    sum += v * v;
                }
                frameEnergy[f] = sum / CepstrumLength;
            }
            double gate = Quantile(frameEnergy, frames, 0.7);

            double[] window = new double[CepstrumLength];
            for (int n = 0; n < CepstrumLength; n++)
            {
                window[n] = 0.5 - 0.5 * Math.Cos(2.0 * Pi * n / CepstrumLength); // torch's periodic default
            }

            FftPlan plan = FftPlan.Get(CepstrumLength);
            int half = CepstrumLength / 2;
            double[] re = new double[CepstrumLength];
            double[] im = new double[CepstrumLength];
            double[] ceps = new double[CepstrumLength];
            int used = 0;

            for (int f = 0; f < frames; f++)
            {
                if (!(frameEnergy[f] > gate)) continue;
                used++;
                int at = f * CepstrumLength;
                for (int n = 0; n < CepstrumLength; n++) re[n] = w[at + n] * window[n];
                for (int n = 0; n < CepstrumLength; n++) im[n] = 0;
                plan.Forward(re, im);

                for (int k = 0; k <= half; k++)
                {
                    double magnitude = Math.Sqrt(re[k] * re[k] + im[k] * im[k]) + 1e-8;
                    re[k] = Math.Log(magnitude);
                }
                double mean = 0;
                for (int k = 0; k <= half; k++) mean += re[k];
                mean /= half + 1;
                for (int k = 0; k <= half; k++) re[k] -= mean;

                // irfft of a real, even spectrum is the forward transform of it mirrored, over N.
                for (int k = half + 1; k < CepstrumLength; k++) re[k] = 0;
                for (int k = 1; k < half; k++) re[CepstrumLength - k] = re[k];
                for (int k = 0; k < CepstrumLength; k++) im[k] = 0;
                plan.Forward(re, im);
                double scale = 1.0 / CepstrumLength;
                for (int k = 0; k < CepstrumLength; k++) ceps[k] += re[k] * scale;
            }
            if (used == 0) return;
            for (int k = 0; k < CepstrumLength; k++) ceps[k] /= used;

            int low = 0;
            while (low < CepstrumLength && !(low / (double)EncoderRate > 1.0 / 300.0)) low++;
            int high = CepstrumLength - 1;
            while (high > 0 && !(high / (double)EncoderRate < 1.0 / F0Min)) high--;
            if (high <= low) return;

            int length = high - low + 1;
            double[] band = new double[length];
            Array.Copy(ceps, low, band, 0, length);
            int index = FundamentalIndex(band, length, low, CepstrumTolerance);
            hz = EncoderRate / (double)(low + index);
            peak = band[index];
        }

        /// <summary>
        /// Speaking-rate proxy: smoothed-energy peaks (roughly syllables) per second of speech over the first
        /// 30 s, counting peaks closer than 80 ms as one syllable.
        /// </summary>
        internal static double Rate(float[] wav, int sampleRate)
        {
            int hop = sampleRate / 100;
            int frames = wav.Length / hop;
            if (frames < 3) return 0;

            double[] energy = new double[frames];
            for (int i = 0; i < frames; i++)
            {
                double sum = 0;
                int at = i * hop;
                for (int n = 0; n < hop; n++)
                {
                    double v = wav[at + n];
                    sum += v * v;
                }
                energy[i] = Math.Sqrt(sum / hop);
            }

            // Three-frame moving average, zero padded at both ends, as avg_pool1d(3, 1, 1) does.
            double[] smooth = new double[frames];
            for (int i = 0; i < frames; i++)
            {
                double sum = energy[i];
                if (i > 0) sum += energy[i - 1];
                if (i + 1 < frames) sum += energy[i + 1];
                smooth[i] = sum / 3.0;
            }

            double max = 0;
            for (int i = 0; i < frames; i++)
            {
                if (smooth[i] > max) max = smooth[i];
            }
            double gate = 0.05 * max;

            int syllables = 0;
            int previous = -1;
            int speech = 0;
            for (int i = 0; i < frames; i++) if (smooth[i] > gate) speech++;

            for (int i = 1; i + 1 < frames; i++)
            {
                if (!(smooth[i] > smooth[i - 1]) || !(smooth[i] >= smooth[i + 1]) || !(smooth[i] > gate)) continue;
                if (previous < 0) syllables = 1;
                else if (i - previous >= 8) syllables++;
                previous = i;
            }
            if (syllables == 0) return 0;

            double speechSeconds = speech / 100.0;
            return syllables / (speechSeconds + 1e-9);
        }

        /// <summary>Spectral tilt in dB per octave: least-squares slope of the mean power spectrum over 300..4000 Hz.</summary>
        internal static double Tilt(float[] wav, int sampleRate)
        {
            float[] mono = Resample(wav, sampleRate, KokoroRate);
            int frames = 1 + mono.Length / TiltHop;

            double[] window = new double[TiltWindow];
            for (int n = 0; n < TiltWindow; n++)
            {
                window[n] = 0.5 - 0.5 * Math.Cos(2.0 * Pi * n / TiltWindow); // periodic, as torch.stft
            }

            FftPlan plan = FftPlan.Get(TiltWindow);
            int bins = TiltWindow / 2 + 1;
            double[] re = new double[TiltWindow];
            double[] im = new double[TiltWindow];
            double[] mean = new double[bins];
            const int pad = TiltWindow / 2;

            for (int f = 0; f < frames; f++)
            {
                int start = f * TiltHop - pad;
                for (int n = 0; n < TiltWindow; n++)
                {
                    int index = start + n;
                    if (index < 0) index = -index;
                    else if (index >= mono.Length) index = 2 * mono.Length - 2 - index;
                    re[n] = (index >= 0 && index < mono.Length ? mono[index] : 0) * window[n];
                    im[n] = 0;
                }
                plan.Forward(re, im);
                for (int k = 0; k < bins; k++) mean[k] += re[k] * re[k] + im[k] * im[k];
            }
            for (int k = 0; k < bins; k++) mean[k] /= frames;

            double binHz = KokoroRate / 2.0 / (bins - 1);
            double sumX = 0;
            double sumY = 0;
            int count = 0;
            for (int k = 0; k < bins; k++)
            {
                double hz = k * binHz;
                if (!(hz > TiltBandLow) || !(hz < TiltBandHigh)) continue;
                sumX += Math.Log(hz) * LnToLog2;
                sumY += 10.0 * Math.Log10(mean[k] + 1e-12);
                count++;
            }
            if (count < 2) return 0;
            double xMean = sumX / count;
            double yMean = sumY / count;

            double covariance = 0;
            double variance = 0;
            for (int k = 0; k < bins; k++)
            {
                double hz = k * binHz;
                if (!(hz > TiltBandLow) || !(hz < TiltBandHigh)) continue;
                double dx = Math.Log(hz) * LnToLog2 - xMean;
                covariance += dx * (10.0 * Math.Log10(mean[k] + 1e-12) - yMean);
                variance += dx * dx;
            }
            return variance > 0 ? covariance / variance : 0;
        }

        // ---------------------------------------------------------------- the blend

        /// <summary>
        /// Nonnegative least squares of the stock packs' prosody stats to the reference's (F0 mean, F0 spread,
        /// syllable rate): the pitch gate drops packs too far away, the grade penalty rows push weight off packs
        /// below C, and a 10x row makes the weights sum to 1.
        /// </summary>
        /// <param name="target">F0 mean in semitones, F0 spread in semitones, syllables per second.</param>
        /// <param name="chosen">Pack indices with a weight above 1e-3, strongest first.</param>
        /// <param name="weights">The same weights, summing to 1 before the 1e-3 floor.</param>
        internal void BlendWeights(double[] target, out int[] chosen, out double[] weights)
        {
            double[] distance = new double[_packCount];
            for (int v = 0; v < _packCount; v++) distance[v] = Math.Abs(_packStats[3 * v] - target[0]);

            bool[] open = new bool[_packCount];
            int openCount = 0;
            for (int v = 0; v < _packCount; v++)
            {
                if (distance[v] <= _blendGate)
                {
                    open[v] = true;
                    openCount++;
                }
            }
            if (openCount < MinimumPacks)
            {
                // Outside the stock pitch range: widen the gate until it reaches the nearest packs.
                double[] sorted = (double[])distance.Clone();
                SortAscending(sorted, _packCount);
                double limit = sorted[MinimumPacks - 1];
                openCount = 0;
                for (int v = 0; v < _packCount; v++)
                {
                    open[v] = distance[v] <= limit;
                    if (open[v]) openCount++;
                }
            }

            int[] columns = new int[openCount];
            int at = 0;
            for (int v = 0; v < _packCount; v++)
            {
                if (open[v]) columns[at++] = v;
            }

            int rows = 4 + openCount; // three stat rows, the sum-to-1 row, one grade-penalty row per pack
            double[] a = new double[rows * openCount];
            double[] b = new double[rows];
            for (int c = 0; c < openCount; c++)
            {
                a[c] = _packStats[3 * columns[c]] / _blendScale[0];
                a[openCount + c] = _packStats[3 * columns[c] + 1] / _blendScale[1];
                a[2 * openCount + c] = _packStats[3 * columns[c] + 2] / _blendScale[2];
                a[3 * openCount + c] = 10.0;
                double penalty = _gradePenalty * Math.Max(0.0, 2.0 - _packGrades[columns[c]]);
                a[(4 + c) * openCount + c] = penalty; // rows 4.. are the grade-penalty diagonal
            }
            b[0] = target[0] / _blendScale[0];
            b[1] = target[1] / _blendScale[1];
            b[2] = target[2] / _blendScale[2];
            b[3] = 10.0;

            double[] solution = NonnegativeLeastSquares(a, rows, openCount, b);
            double total = 0;
            for (int i = 0; i < solution.Length; i++) total += solution[i];
            if (!(total > 0))
            {
                throw new InvalidOperationException("The blend collapsed to zero weight on every stock pack.");
            }

            List<int> keep = new List<int>(openCount);
            List<double> values = new List<double>(openCount);
            for (int i = 0; i < solution.Length; i++)
            {
                double value = solution[i] / total;
                if (value > WeightFloor)
                {
                    keep.Add(columns[i]);
                    values.Add(value);
                }
            }
            if (keep.Count == 0)
            {
                // Cannot happen with weights that sum to 1, but a silent empty pack would be worse than a throw.
                throw new InvalidOperationException("The blend produced no pack above " + WeightFloor + ".");
            }

            int[] chosenIndex = keep.ToArray();
            double[] chosenWeight = values.ToArray();
            for (int i = 1; i < chosenWeight.Length; i++)
            {
                for (int j = i; j > 0 && chosenWeight[j] > chosenWeight[j - 1]; j--)
                {
                    double w = chosenWeight[j];
                    chosenWeight[j] = chosenWeight[j - 1];
                    chosenWeight[j - 1] = w;
                    int p = chosenIndex[j];
                    chosenIndex[j] = chosenIndex[j - 1];
                    chosenIndex[j - 1] = p;
                }
            }
            chosen = chosenIndex;
            weights = chosenWeight;
        }

        /// <summary>
        /// Lawson-Hanson nonnegative least squares: repeatedly solve the unconstrained problem over the passive
        /// set and pull back the step length that would drive a coefficient negative, until the negative gradient
        /// has no candidate left. Matches scipy.optimize.nnls on these well-conditioned, few-column problems.
        /// </summary>
        internal static double[] NonnegativeLeastSquares(double[] a, int rows, int columns, double[] b)
        {
            double[] x = new double[columns];
            bool[] passive = new bool[columns];
            double[] gradient = new double[columns];

            Gradient(a, rows, columns, b, x, gradient);

            // A negative-gradient entry is a candidate for the passive set; below this the entry cannot move a
            // coefficient that the 6-decimal report would show.
            double normA = 0;
            double normB = 0;
            for (int i = 0; i < a.Length; i++) normA += a[i] * a[i];
            for (int i = 0; i < rows; i++) normB = Math.Max(normB, Math.Abs(b[i]));
            double tolerance = 1e-13 * Math.Sqrt(normA) * normB;

            int maxIterations = 30 * columns;
            for (int iteration = 0; iteration < maxIterations; iteration++)
            {
                int enter = -1;
                double best = tolerance;
                for (int j = 0; j < columns; j++)
                {
                    if (!passive[j] && gradient[j] > best)
                    {
                        best = gradient[j];
                        enter = j;
                    }
                }
                if (enter < 0) break;
                passive[enter] = true;

                for (int inner = 0; inner < maxIterations; inner++)
                {
                    int count = 0;
                    for (int j = 0; j < columns; j++) if (passive[j]) count++;

                    int[] index = new int[count];
                    int at = 0;
                    for (int j = 0; j < columns; j++) if (passive[j]) index[at++] = j;

                    // Least squares over the passive columns only, by Householder QR.
                    double[] sub = new double[rows * count];
                    for (int r = 0; r < rows; r++)
                    {
                        for (int c = 0; c < count; c++) sub[r * count + c] = a[r * columns + index[c]];
                    }
                    double[] candidate;
                    LeastSquares(sub, rows, count, b, out candidate);

                    double[] z = new double[columns];
                    for (int c = 0; c < count; c++) z[index[c]] = candidate[c];

                    bool feasible = true;
                    for (int c = 0; c < count; c++)
                    {
                        if (!(z[index[c]] > 0)) feasible = false;
                    }
                    if (feasible)
                    {
                        Array.Copy(z, x, columns);
                        break;
                    }

                    double alpha = Huge;
                    for (int c = 0; c < count; c++)
                    {
                        int j = index[c];
                        if (z[j] <= 0)
                        {
                            double denominator = x[j] - z[j];
                            double step = denominator > 0 ? x[j] / denominator : 0;
                            if (step < alpha) alpha = step;
                        }
                    }
                    if (alpha == Huge) alpha = 0;

                    double sum = 0;
                    for (int c = 0; c < count; c++)
                    {
                        int j = index[c];
                        x[j] += alpha * (z[j] - x[j]);
                        if (x[j] < 0) x[j] = 0;
                        sum += x[j];
                    }
                    // Hold the coefficients at exactly zero where the step drove them there, so they leave the
                    // passive set.
                    for (int c = 0; c < count; c++)
                    {
                        int j = index[c];
                        if (x[j] <= 0)
                        {
                            x[j] = 0;
                            passive[j] = false;
                        }
                    }
                    if (!(sum > 0))
                    {
                        for (int c = 0; c < count; c++) x[index[c]] = 0;
                        break;
                    }
                }

                Gradient(a, rows, columns, b, x, gradient);
            }
            return x;
        }

        private static void Gradient(double[] a, int rows, int columns, double[] b, double[] x, double[] gradient)
        {
            for (int j = 0; j < columns; j++) gradient[j] = 0;
            for (int r = 0; r < rows; r++)
            {
                double residual = b[r];
                int row = r * columns;
                for (int j = 0; j < columns; j++) residual -= a[row + j] * x[j];
                for (int j = 0; j < columns; j++) gradient[j] += a[row + j] * residual;
            }
        }

        /// <summary>Least squares by Householder QR on a column-major-safe row-major copy of A.</summary>
        private static void LeastSquares(double[] a, int rows, int columns, double[] b, out double[] x)
        {
            double[] r = (double[])a.Clone();
            double[] y = (double[])b.Clone();

            for (int k = 0; k < columns; k++)
            {
                double norm = 0;
                for (int i = k; i < rows; i++) norm += r[i * columns + k] * r[i * columns + k];
                norm = Math.Sqrt(norm);
                if (norm == 0) continue;
                double alpha = r[k * columns + k] > 0 ? -norm : norm;
                double[] v = new double[rows - k];
                for (int i = k; i < rows; i++) v[i - k] = r[i * columns + k];
                v[0] -= alpha;
                double vv = 0;
                for (int i = 0; i < v.Length; i++) vv += v[i] * v[i];
                if (vv == 0) continue;
                double beta = 2.0 / vv;
                for (int j = k; j < columns; j++)
                {
                    double dot = 0;
                    for (int i = k; i < rows; i++) dot += v[i - k] * r[i * columns + j];
                    double factor = beta * dot;
                    for (int i = k; i < rows; i++) r[i * columns + j] -= factor * v[i - k];
                }
                double dotB = 0;
                for (int i = k; i < rows; i++) dotB += v[i - k] * y[i];
                double factorB = beta * dotB;
                for (int i = k; i < rows; i++) y[i] -= factorB * v[i - k];
            }

            x = new double[columns];
            for (int i = columns - 1; i >= 0; i--)
            {
                double sum = y[i];
                for (int j = i + 1; j < columns; j++) sum -= r[i * columns + j] * x[j];
                double diagonal = r[i * columns + i];
                x[i] = diagonal != 0 ? sum / diagonal : 0;
            }
        }

