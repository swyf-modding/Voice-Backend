        /// <summary>Insertion sort of the first <paramref name="count"/> entries, ascending.</summary>
        private static void SortAscending(double[] values, int count)
        {
            for (int i = 1; i < count; i++)
            {
                double v = values[i];
                int j = i - 1;
                while (j >= 0 && values[j] > v)
                {
                    values[j + 1] = values[j];
                    j--;
                }
                values[j + 1] = v;
            }
        }

        /// <summary>Linear-interpolated quantile over the first <paramref name="count"/> entries, as torch.quantile.</summary>
        private static double Quantile(double[] values, int count, double q)
        {
            if (count <= 0) return 0;
            if (count == 1) return values[0];
            double[] sorted = new double[count];
            Array.Copy(values, sorted, count);
            SortAscending(sorted, count);
            double position = q * (count - 1);
            int low = (int)Math.Floor(position);
            int high = low + 1 < count ? low + 1 : count - 1;
            double fraction = position - low;
            return sorted[low] + fraction * (sorted[high] - sorted[low]);
        }

        /// <summary>The lower median, which is what torch.median returns for an even count.</summary>
        private static double LowerMedian(double[] values, int count, double[] scratch)
        {
            Array.Copy(values, scratch, count);
            SortAscending(scratch, count);
            return scratch[(count - 1) / 2];
        }

        /// <summary>
        /// IEEE half to float, without BitConverter or bit punning (this mscorlib has neither the reinterpretation
        /// overloads nor a NaN constant). Only normal and subnormal halves are handled: <see cref="ReadTables"/>
        /// rejects anything else before a row reaches here.
        /// </summary>
        private static float HalfToFloat(ushort bits)
        {
            int exponent = (bits >> 10) & 0x1F;
            int mantissa = bits & 0x3FF;
            float value = exponent == 0
                ? mantissa * 5.9604645E-08f // 2^-24, for the subnormals
                : (1024 + mantissa) * Pow2(exponent - 25);
            return (bits & 0x8000) != 0 ? -value : value;
        }

        private static float Pow2(int exponent)
        {
            // Only -24..6 reach here for a half's normal range; exact powers of two, so no libm call.
            if (exponent >= -24 && exponent <= 6) return _pow2[exponent + 24];
            return (float)Math.Pow(2.0, exponent);
        }

        private static readonly float[] _pow2 = BuildPow2();

        private static float[] BuildPow2()
        {
            float[] values = new float[31];
            float v = 5.9604645E-08f; // 2^-24
            for (int i = 0; i < values.Length; i++)
            {
                values[i] = v;
                v *= 2f;
            }
            return values;
        }

        /// <summary>Twiddle and bit-reversal tables for one power-of-two FFT size, built once and shared.</summary>
        private sealed class FftPlan
        {
            private static readonly Dictionary<int, FftPlan> Cache = new Dictionary<int, FftPlan>();
            private static readonly object CacheLock = new object();

            private readonly int _n;
            private readonly int[] _reverse;
            private readonly double[] _cos;
            private readonly double[] _sin;

            private FftPlan(int n)
            {
                _n = n;
                _reverse = new int[n];
                int bits = 0;
                while ((1 << bits) < n) bits++;
                for (int i = 0; i < n; i++)
                {
                    int r = 0;
                    for (int b = 0; b < bits; b++)
                    {
                        if ((i & (1 << b)) != 0) r |= 1 << (bits - 1 - b);
                    }
                    _reverse[i] = r;
                }
                _cos = new double[n / 2];
                _sin = new double[n / 2];
                for (int i = 0; i < n / 2; i++)
                {
                    _cos[i] = Math.Cos(2.0 * Pi * i / n);
                    _sin[i] = Math.Sin(2.0 * Pi * i / n);
                }
            }

            internal static FftPlan Get(int n)
            {
                lock (CacheLock)
                {
                    FftPlan plan;
                    if (!Cache.TryGetValue(n, out plan))
                    {
                        plan = new FftPlan(n);
                        Cache[n] = plan;
                    }
                    return plan;
                }
            }

            /// <summary>In-place forward transform of a real/imaginary pair of length n.</summary>
            internal void Forward(double[] re, double[] im)
            {
                int n = _n;
                for (int i = 0; i < n; i++)
                {
                    int j = _reverse[i];
                    if (j > i)
                    {
                        double t = re[i];
                        re[i] = re[j];
                        re[j] = t;
                        t = im[i];
                        im[i] = im[j];
                        im[j] = t;
                    }
                }
                for (int size = 2; size <= n; size *= 2)
                {
                    int halfSize = size / 2;
                    int step = n / size;
                    for (int i = 0; i < n; i += size)
                    {
                        for (int j = i, k = 0; j < i + halfSize; j++, k += step)
                        {
                            double c = _cos[k];
                            double s = _sin[k];
                            int other = j + halfSize;
                            double tre = re[other] * c + im[other] * s;
                            double tim = im[other] * c - re[other] * s;
                            re[other] = re[j] - tre;
                            im[other] = im[j] - tim;
                            re[j] += tre;
                            im[j] += tim;
                        }
                    }
                }
            }
        }
    }
